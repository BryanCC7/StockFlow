-- StockFlow schema (H2 portable, JPA-compatible con Postgres)
-- Orden: entidades sin FK primero

DROP TABLE IF EXISTS detalle_pedido;
DROP TABLE IF EXISTS pedido;
DROP TABLE IF EXISTS producto;
DROP TABLE IF EXISTS cliente;

CREATE TABLE cliente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL,
  telefono VARCHAR(40),
  version BIGINT,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP,
  CONSTRAINT uq_cliente_email UNIQUE (email)
);

CREATE TABLE producto (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(140) NOT NULL,
  categoria VARCHAR(80),
  precio DECIMAL(12,2) NOT NULL CHECK (precio > 0),
  stock_actual INT NOT NULL CHECK (stock_actual >= 0),
  version BIGINT,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP
);
CREATE INDEX idx_producto_categoria ON producto (categoria);
CREATE INDEX idx_producto_precio ON producto (precio);

CREATE TABLE pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL,
  fecha TIMESTAMP NOT NULL,
  estado VARCHAR(20) NOT NULL,
  total DECIMAL(14,2) NOT NULL,
  version BIGINT,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP,
  CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);
CREATE INDEX idx_pedido_cliente ON pedido (cliente_id);
CREATE INDEX idx_pedido_fecha ON pedido (fecha);

CREATE TABLE detalle_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL,
  producto_id BIGINT NOT NULL,
  cantidad INT NOT NULL CHECK (cantidad >= 1),
  precio_unitario DECIMAL(12,2) NOT NULL,
  version BIGINT,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP,
  CONSTRAINT fk_detalle_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
  CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);
CREATE INDEX idx_detalle_pedido ON detalle_pedido (pedido_id);
CREATE INDEX idx_detalle_producto ON detalle_pedido (producto_id);
